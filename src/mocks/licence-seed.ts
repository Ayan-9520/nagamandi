import type { LicenceCase, LicenceChecklist, LicenceData, LicenceDocument, LicenceEvent } from '@/types/licence'

const AT = '2026-11-14T08:30:00+05:30'
const MANDI = 'mandi-dimapur'

function doc(id: string, slot: LicenceDocument['slot'], name: string): LicenceDocument {
  return { id, slot, name, mimeType: 'text/plain', size: 120, previewDataUrl: null, addedAt: AT }
}

function papers(id: string): LicenceDocument[] {
  return [
    doc(`${id}-id`, 'identity', `${id}-identity.txt`),
    doc(`${id}-br`, 'registration', `${id}-registration.txt`),
    doc(`${id}-tax`, 'tax', `${id}-tax.txt`),
  ]
}

function pendingChecklist(): LicenceChecklist {
  return {
    identity: 'pending',
    registration: 'pending',
    tax: 'pending',
    additional: 'pending',
    formComplete: 'pending',
    documentsAttached: 'pending',
    remarks: '',
  }
}

function passedChecklist(remarks: string): LicenceChecklist {
  return {
    identity: 'pass',
    registration: 'pass',
    tax: 'pass',
    additional: 'pending',
    formComplete: 'pass',
    documentsAttached: 'pass',
    remarks,
  }
}

function event(id: string, title: string, detail: string): LicenceEvent {
  return { id, at: AT, title, detail }
}

function base(partial: Pick<LicenceCase, 'id' | 'kind' | 'status' | 'category' | 'partyId' | 'ownerAccountId' | 'applicantLabel' | 'area' | 'phone' | 'email' | 'businessName' | 'businessArea' | 'registrationNo' | 'taxId'> & Partial<LicenceCase>): LicenceCase {
  return {
    mandiId: MANDI,
    documents: papers(partial.id),
    checklist: pendingChecklist(),
    officerNote: '',
    managerNote: '',
    clarificationNote: '',
    clarificationFrom: '',
    rejectionNote: '',
    fee: emptyFee(partial.category),
    licenceNo: null,
    issuedAt: null,
    validFrom: null,
    validUntil: null,
    parentId: null,
    supersededBy: null,
    qrPayload: null,
    events: [event(`EVT-${partial.id}-load`, 'Sample loaded', 'This application was placed in the demonstration register. It is not an office filing.')],
    createdAt: AT,
    updatedAt: AT,
    ...partial,
  }
}

